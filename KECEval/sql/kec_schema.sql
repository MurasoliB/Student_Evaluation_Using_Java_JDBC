DROP DATABASE IF EXISTS kec_eval;
CREATE DATABASE kec_eval CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kec_eval;

-- 1. Students Table
CREATE TABLE students (
    roll_no VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    department VARCHAR(20) NOT NULL,
    current_semester INT NOT NULL DEFAULT 3 CHECK (current_semester BETWEEN 1 AND 8),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Course Catalog Table
CREATE TABLE courses (
    course_code VARCHAR(20) PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    credits INT NOT NULL CHECK (credits >= 0),
    course_type ENUM('THEORY', 'PRACTICAL', 'EMBEDDED') NOT NULL,
    semester INT NOT NULL DEFAULT 3 CHECK (semester BETWEEN 1 AND 8),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Enrollments & Attendance Tracking Table
CREATE TABLE enrollments (
    enrollment_id INT AUTO_INCREMENT PRIMARY KEY,
    roll_no VARCHAR(20) NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    semester INT NOT NULL DEFAULT 3 CHECK (semester BETWEEN 1 AND 8),
    total_classes INT NOT NULL DEFAULT 0 CHECK (total_classes >= 0),
    attended_classes INT NOT NULL DEFAULT 0 CHECK (attended_classes >= 0),
    is_condoned BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_enrollment_student FOREIGN KEY (roll_no) REFERENCES students(roll_no) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_enrollment_course FOREIGN KEY (course_code) REFERENCES courses(course_code) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uk_student_course_sem UNIQUE (roll_no, course_code, semester),
    CONSTRAINT chk_attendance_valid CHECK (attended_classes <= total_classes)
);

-- 4. Phased Assessment Marks Table
CREATE TABLE assessment_marks (
    mark_id INT AUTO_INCREMENT PRIMARY KEY,
    enrollment_id INT NOT NULL UNIQUE,
    cia1_marks DECIMAL(5,2) NULL CHECK (cia1_marks IS NULL OR (cia1_marks >= 0 AND cia1_marks <= 100)),
    cia2_marks DECIMAL(5,2) NULL CHECK (cia2_marks IS NULL OR (cia2_marks >= 0 AND cia2_marks <= 100)),
    assignment_marks DECIMAL(5,2) NULL CHECK (assignment_marks IS NULL OR (assignment_marks >= 0 AND assignment_marks <= 100)),
    ese_marks DECIMAL(5,2) NULL CHECK (ese_marks IS NULL OR (ese_marks >= 0 AND ese_marks <= 100)),
    is_ese_absent BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assessment_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments(enrollment_id) ON DELETE CASCADE ON UPDATE CASCADE
);

